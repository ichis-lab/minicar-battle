#ifndef CONFIG_H
#define CONFIG_H

// ============================================================================
// デバッグモード設定
// ============================================================================
#define DEBUG_MODE false  // true: デバッグ（PWMなし、シリアルあり）
                          // false: 実機（PWMあり、シリアルなし）

// ============================================================================
// ハードウェア設定
// ============================================================================
// TCA9548A I2Cマルチプレクサ
const uint8_t TCA9548A_ADDR = 0x70;

// センサー設定
const uint8_t NUM_SENSORS = 5;
const uint8_t SENSOR_CHANNELS[NUM_SENSORS] = {0, 1, 2, 3, 4};
const float SENSOR_ANGLES[NUM_SENSORS] = {-70.0, -20.0, 0.0, 20.0, 70.0};

// PWM出力ピン
const uint8_t SERVO_PIN = 9;   // ステアリングサーボ
const uint8_t ESC_PIN = 10;    // ESC（モーター制御）

// ============================================================================
// VL53L1X センサーパラメータ
// ============================================================================
const uint16_t MIN_VALID_DISTANCE = 50;        // 最小有効測定距離（mm）
const uint16_t RELIABLE_RANGE = 4000;          // 信頼できる測定範囲（mm）L1Xは最大4m
const uint16_t MAX_SENSOR_DIFF = 600;          // センサーペア間の最大許容差（mm）

// VL53L1X タイミング設定
const uint32_t L1X_TIMING_BUDGET_US = 50000;   // 測定時間（μs）50ms
const uint32_t L1X_INTER_MEASUREMENT_MS = 50;  // 測定間隔（ms）

// ============================================================================
// タイミング設定
// ============================================================================
const unsigned long MEASUREMENT_INTERVAL = 60;  // 60ms（L1X測定間隔以上を推奨）

// ============================================================================
// ステアリングパラメータ
// ============================================================================
const float MAX_STEERING_ANGLE = 30.0;         // 最大操舵角（度）

// ============================================================================
// PID パラメータ（両壁モード：距離制御）
// ============================================================================
const float STEERING_KP = 0.08;               // 比例ゲイン（deg/mm）
const float STEERING_KI = 0.05;              // 積分ゲイン
const float STEERING_KD = 0.02;               // 微分ゲイン
const float STEERING_INTEGRAL_MAX = 50.0;     // 積分上限（アンチワインドアップ）

// 目標壁距離（両壁検出時）
const float TARGET_CENTER_OFFSET = 0.0;       // 中央からのオフセット（mm）

// ===========================================================================
// PID パラメータ（片壁モード：角度制御）
// ============================================================================
const float ANGLE_KP = 0.8;                   // 比例ゲイン（deg/deg）
const float ANGLE_KI = 0.05;                   // 積分ゲイン（まず0で開始）
const float ANGLE_KD = 0.1;                   // 微分ゲイン

// ============================================================================
// 安全パラメータ
// ============================================================================
const uint16_t MIN_SAFE_DISTANCE = 300;       // 最低安全距離（mm）左右共通
const float DISTANCE_AVOID_GAIN = 0.15;       // 距離制約ゲイン
const uint16_t EMERGENCY_FRONT_THRESHOLD = 200;  // 前方緊急閾値（mm）

// ============================================================================
// 微分フィルタ
// ============================================================================
const float DERIVATIVE_FILTER_ALPHA = 0.3;    // フィルタ係数（0-1、小さいほど強いフィルタ）

// ============================================================================
// サーボ・ESC パルス幅設定
// ============================================================================
// サーボ（ステアリング）
const uint16_t SERVO_CENTER = 1510;           // 中央位置（μs）+10でちょい右に修正
const uint16_t SERVO_MIN = 600;               // 最小パルス幅（μs）
const uint16_t SERVO_MAX = 2400;              // 最大パルス幅（μs）

// ESC（速度制御）
const float STOP_SPEED_PULSE = 1.5;           // 停止（ms）
const float BASE_SPEED_PULSE = 1.45;          // 基本速度（ms）
const uint16_t ESC_MIN_US = 1000;             // ESC最小パルス（μs）
const uint16_t ESC_MAX_US = 2000;             // ESC最大パルス（μs）

#endif // CONFIG_H
